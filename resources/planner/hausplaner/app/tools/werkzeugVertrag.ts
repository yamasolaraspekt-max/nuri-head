/**
 * AUF-36 — der **Funktionsvertrag** der 110 Werkzeuge als typisierte Daten.
 *
 * **Was das ist:** Je Werkzeug beschreibt der Vertrag, *was* es täte — `commandId`, Familie,
 * Eingaben, Ergebnisse, Vorbedingungen, Seiteneffekte, ob es umkehrbar und protokollpflichtig ist,
 * und welche Dienstmethode es rufen würde. **Es ist eine Beschreibung, keine Ausführung.**
 *
 * **Die Grenze, und sie ist die wichtigste Zeile dieses Moduls:** Hier entsteht **kein zweiter
 * Ausführungsweg.** Es gibt kein `runTool`, keinen Dispatcher, keine Stelle, die `dienstMethode`
 * aufruft. Jede Änderung am Modell läuft weiterhin ausschließlich über `applyCommand` mit inversen
 * Immer-Patches und `CommandAbgelehnt` **vor** der Mutation. Ein zweiter Weg daneben verlöre Undo
 * und die Ablehnungsprüfung — das wäre der teuerste Fehler des ganzen Pakets. `commandId`,
 * `umkehrbar` und `protokollpflichtig` sind **Metadaten am Werkzeug**, sonst nichts.
 *
 * **Warum ein eigenes Modul und kein Feld an `ToolDefinition`:** I2 hat zugesagt, kein Feld der
 * Bestandsform zu ändern oder zu ergänzen; die Richtung der Anpassung ist Vorschrift (Bauordnung,
 * Konflikt-Regel). Der Vertrag hängt deshalb **neben** der Werkzeugdefinition und wird über die id
 * verbunden.
 *
 * **Erzeugt aus** `~/Downloads/hausplaner_svg_tool_functions.zip` → `src/tool-registry.json`,
 * Feld `code`. Die englischen Paket-ids sind über die führende Namenstabelle
 * `docs/planner/eindeutschung-110-paket-ids.md` auf die deutschen UI-ids abgebildet (AUF-31).
 * `commandId` und `dienstMethode` bleiben englisch — das sind **technische Bezeichner** des
 * Vertrags, keine Beschriftungen, die jemand sieht.
 */

export interface WerkzeugVertrag {
  /** Deutsche UI-id des Werkzeugs (AUF-31) — die Klammer zur `ToolDefinition`. */
  werkzeugId: string;
  /** Technischer Command-Name aus dem Vertrag, z. B. `WallCommand`. Metadatum, kein Aufruf. */
  commandId: string;
  /** Eine von 9 Familien: selection · create · modify · view · measurement · import · domain · assign-or-calculate · workflow. */
  familie: string;
  eingaben: readonly string[];
  ergebnisse: readonly string[];
  /** Eine von 12 Vorbedingungen — die Zuordnung zur Aktivierung steht in `vorbedingungen.ts`. */
  vorbedingungen: readonly string[];
  seiteneffekte: readonly string[];
  /** Rückgängig möglich? Metadatum; die Umkehr leistet `applyCommand` über inverse Patches. */
  umkehrbar: boolean;
  /** Protokollpflichtig? Metadatum; ein Audit-Trail wird hier NICHT geschrieben. */
  protokollpflichtig: boolean;
  /** Die Dienstmethode, die dieses Werkzeug rufen WÜRDE. Wird von niemandem aufgerufen. */
  dienstMethode: string;
}

