const NACH_ID = new Map(WERKZEUG_VERTRAEGE.map((v) => [v.werkzeugId, v]));

/** Der Vertrag eines Werkzeugs (oder undefined). */
export function vertrag(werkzeugId: string): WerkzeugVertrag | undefined {
  return NACH_ID.get(werkzeugId);
}

/** Alle Verträge einer Familie. */
export function vertraegeDerFamilie(familie: string): WerkzeugVertrag[] {
  return WERKZEUG_VERTRAEGE.filter((v) => v.familie === familie);
}

/** Die Vokabulare, gezählt aus den Daten — nicht hart hinterlegt, damit sie nicht auseinanderlaufen. */
export function vokabular(): { vorbedingungen: string[]; seiteneffekte: string[]; familien: string[] } {
  const sammle = (f: (v: WerkzeugVertrag) => readonly string[]): string[] =>
    [...new Set(WERKZEUG_VERTRAEGE.flatMap((v) => f(v)))].sort();
  return {
    vorbedingungen: sammle((v) => v.vorbedingungen),
    seiteneffekte: sammle((v) => v.seiteneffekte),
    familien: sammle((v) => [v.familie]),
  };
}

/** Werkzeug-ids mit mehr als einem Vertrag — muss leer sein. */
export function doppelteVertraege(): string[] {
  const zaehler = new Map<string, number>();
  for (const v of WERKZEUG_VERTRAEGE) zaehler.set(v.werkzeugId, (zaehler.get(v.werkzeugId) ?? 0) + 1);
  return [...zaehler].filter(([, n]) => n > 1).map(([id]) => id);
}
